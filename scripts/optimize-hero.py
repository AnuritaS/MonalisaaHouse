"""Run after replacing collage JPGs: python scripts/optimize-hero.py (requires Pillow)."""
from pathlib import Path
from hashlib import sha256
from PIL import Image, ImageOps
import json
import re

root = Path(__file__).resolve().parent.parent
output = root / 'images' / 'optimized'
output.mkdir(exist_ok=True)
html = (root / 'index.html').read_text()
paths = []
original_size = 0
for number in range(1, 16):
    name = f'collage-{number:02}'
    original = root / 'images' / f'{name}.jpg'
    original_size += original.stat().st_size
    with Image.open(original) as image:
        image = ImageOps.exif_transpose(image).convert('RGB')
        image.thumbnail((640, 640), Image.Resampling.LANCZOS)
        temporary = output / f'{name}.webp'
        image.save(temporary, 'WEBP', quality=78, method=6)
    digest = sha256(temporary.read_bytes()).hexdigest()[:12]
    target = output / f'{name}.{digest}.webp'
    temporary.replace(target)
    # Update either the original JPG or a previously generated WebP reference.
    html = re.sub(rf'<img src=(?:"images/(?:optimized/)?{name}[^" ]*"|images/{name}\.jpg)(?:[^>]*)>',
                  f'<img src="images/optimized/{target.name}" alt="" loading="eager" decoding="async" width="{image.width}" height="{image.height}">', html)
    paths.append(f'images/optimized/{target.name}')
(root / 'index.html').write_text(html)
version = sha256(''.join(paths).encode()).hexdigest()[:12]
(root / 'hero-assets.js').write_text('/* Generated by scripts/optimize-hero.py. */\nconst HERO_CACHE = ' + json.dumps('monalisaa-hero-' + version) + ';\nconst HERO_ASSETS = ' + json.dumps(paths, indent=2) + ';\n')
print(f'Hero images: {original_size:,} bytes -> {sum((root / p).stat().st_size for p in paths):,} bytes')
